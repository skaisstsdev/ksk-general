import { extendTailwindMerge } from "tailwind-merge";

/**
 * Именованные ступени из `src/app/globals.css` (`@theme`), которые
 * `tailwind-merge` не знает сам по себе.
 *
 * Так же, как размерные словосочетания в теле функции: если в globals.css
 * появится новая ступень шкалы отступов или шрифта, её нужно добавить
 * и сюда — иначе конфликт с этой конкретной ступенью снова перестанет
 * разрешаться предсказуемо, тем же способом, каким это уже один раз
 * случилось (см. комментарий к `cn` ниже).
 */
const SPACING_SCALE = [
  "3xs",
  "2xs",
  "xs",
  "sm",
  "md",
  "lg",
  "xl",
  "2xl",
  "3xl",
  "4xl",
  // паузы между блоками — та же шкала, отдельные имена
  "beat",
  "break",
  "turn",
];

const FONT_SIZE_SCALE = [
  "eyebrow",
  "caption",
  "meta",
  "ui",
  "body",
  "lead",
  "subhead",
  "h4",
  "h3",
  "h2",
  "h1",
  "display",
];

const merge = extendTailwindMerge({
  extend: {
    // `m-`/`p-`/`gap-`/логические отступы (`ps-`, `pe-`…) и `w-`/`h-`
    // в Tailwind считаются с одной и той же шкалы отступов — расширяем
    // её один раз, и разрешение конфликтов работает во всех них сразу.
    theme: { spacing: SPACING_SCALE },
    // `text-*` в Tailwind двусмысленно: и цвет, и размер шрифта.
    // Цвет `tailwind-merge` распознаёт сам (любое имя темы), а размер —
    // только по списку ожидаемых ключевых слов, и наши имена в этот
    // список не входили.
    classGroups: { "font-size": [{ text: FONT_SIZE_SCALE }] },
  },
});

/**
 * Склейка классов с разрешением конфликтов.
 *
 * Раньше это была простая конкатенация строк (`filter(Boolean).join(" ")`),
 * и это молча ломалось: компонент задаёт цвет по умолчанию как обычный
 * класс (`text-violet` в `Eyebrow`), вызывающий код передаёт свой цвет
 * через `className`, и обе строки просто складываются рядом в атрибуте.
 * Побеждает не тот класс, что стоит позже в JSX, а тот, чьё CSS-правило
 * Tailwind поставил позже в скомпилированной таблице стилей — а это
 * зависит от порядка сканирования файлов и не гарантировано вообще ничем.
 *
 * На практике это уже стреляло: `<Eyebrow className="text-paper/85">`
 * в хиро поверх фотографии рендерился фиолетовым (цветом по умолчанию),
 * и это не было видно на глаз при беглом просмотре — обнаружилось только
 * при программном замере контраста. Простой установки `tailwind-merge`
 * по умолчанию было мало: она понимает цвет любого имени темы, но
 * значения размера шрифта и отступов сверяет со списком ожидаемых
 * ключевых слов, а наши шкалы (`eyebrow…h1`, `3xs…4xl`, `beat…turn`)
 * в этот список не входят «из коробки» — конфигурация выше их туда
 * добавляет, и с ней конфликт снова решается предсказуемо, а не
 * по случайности сборки.
 */
export function cn(...parts: Array<string | false | null | undefined>) {
  return merge(parts.filter(Boolean).join(" "));
}
